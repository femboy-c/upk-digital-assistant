def seed_database(db: Session) -> None:
    """Наполняет базу, если она ещё пустая."""
    if db.scalar(select(Category).limit(1)) is None:
        for name, description in CATEGORIES:
            db.add(Category(name=name, description=description))

    if db.scalar(select(Location).limit(1)) is None:
        for floor, room, zone_name, qr_key in LOCATIONS:
            db.add(Location(floor=floor, room=room, zone_name=zone_name, qr_key=qr_key))

    if db.scalar(select(User).limit(1)) is None:
        if IS_PRODUCTION:
            # В production демонстрационные пароли недопустимы.
            logger.warning(
                "APP_ENV=production: демо-пользователи не созданы. "
                "Создайте администратора через scripts/create_user.py."
            )
        else:
            for name, login, role, password in USERS:
                db.add(User(name=name, login=login, role=role, password_hash=hash_password(password)))

    # Базу знаний дополняем недостающими записями, не удаляя существующие.
    existing_questions = set(db.scalars(select(KnowledgeBase.question)).all())
    for question, answer, category, source in KNOWLEDGE:
        if question not in existing_questions:
            db.add(KnowledgeBase(question=question, answer=answer, category=category, source=source))

    db.commit()
